#!/bin/sh
# Rebuilds lib/sample.js from the pictures in assets/. Each is shrunk to at most
# 720px on its long side (the frame size) and stored as WebP, lossy or lossless,
# whichever is smaller (lossless wins for pixel art). The app picks one at random
# on start. Needs ffmpeg on PATH.
cd "$(dirname "$0")"
t="${TMPDIR:-/tmp}/wiggle-sample"
fit="scale='min(720,iw)':'min(720,ih)':force_original_aspect_ratio=decrease:flags=lanczos"
{
  echo "// Generated by make_samples.sh from assets/ - do not edit by hand."
  echo "window.SAMPLE_IMAGES = ["
  for f in assets/*.png; do
    ffmpeg -v error -y -i "$f" -vf "$fit" -c:v libwebp -quality 90 -compression_level 6 "$t-lossy.webp"
    ffmpeg -v error -y -i "$f" -vf "$fit" -c:v libwebp -lossless 1 -compression_level 6 "$t-lossless.webp"
    best="$t-lossy.webp"
    [ "$(wc -c < "$t-lossless.webp")" -lt "$(wc -c < "$best")" ] && best="$t-lossless.webp"
    printf '  "data:image/webp;base64,%s",\n' "$(base64 -w0 "$best")"
  done
  echo "];"
} > lib/sample.js
